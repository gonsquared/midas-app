import { createHmac } from 'node:crypto';
import { isIP } from 'node:net';
import {
  addDays,
  type AuditAction,
  type AuditLogEntry,
  type AuditLogPage,
  type AuditTargetType,
  type ListAuditLogsQuery,
} from '@midas/shared';
import type { FastifyRequest } from 'fastify';
import type { Kysely } from 'kysely';
import { v7 as uuidv7 } from 'uuid';
import type { Clock } from '../../platform/clock.js';
import type { DbHandle } from '../../platform/db/client.js';
import type { Database } from '../../platform/db/database.js';
import type { Counter } from '../../platform/metrics.js';
import { decodeAuditCursor, encodeAuditCursor } from './cursor.js';
import { sanitizeAuditMetadata } from './metadata.js';
import { createAuditRepository, type AuditRow } from './repository.js';

declare module 'fastify' {
  interface FastifyRequest {
    /**
     * Always generated by the server (never taken from a header). Audit rows store this id, so a
     * client cannot forge or collide request ids in the trail. The client's own X-Request-Id stays
     * `request.id` (logs and response header only) and is logged next to this one.
     */
    serverRequestId: string;
  }
}

const USER_AGENT_MAX = 512;
const REQUEST_ID = /^[A-Za-z0-9-]{8,64}$/;

/** Where a request came from. Optional everywhere: the scheduler and the CLI have no request. */
export interface AuditContext {
  ip?: string | null | undefined;
  userAgent?: string | null | undefined;
  requestId?: string | null | undefined;
}

export interface AuditEntry {
  actorUserId: string | null;
  action: AuditAction;
  targetType: AuditTargetType;
  targetId?: string | null;
  /** Small hand-built object; never secrets, amounts, notes or transaction details. */
  metadata?: Record<string, unknown>;
  context?: AuditContext | undefined;
}

/** What the auth module needs: record an event and never throw (database design C-07). */
export interface AuditRecorder {
  record(entry: AuditEntry): Promise<void>;
  /** HMAC pseudonym of an email, or undefined when no AUDIT_HMAC_SECRET is configured. */
  pseudonymize(email: string): string | undefined;
}

export const noopAuditRecorder: AuditRecorder = {
  record: async () => undefined,
  pseudonymize: () => undefined,
};

export function auditContext(request: FastifyRequest): AuditContext {
  const userAgent = request.headers['user-agent'];
  return {
    ip: request.ip,
    userAgent: typeof userAgent === 'string' ? userAgent : null,
    requestId: request.serverRequestId,
  };
}

interface Logger {
  error(obj: Record<string, unknown>, msg: string): void;
}

export interface AuditServiceDeps {
  db: Kysely<Database>;
  clock: Clock;
  logger?: Logger | undefined;
  failures?: Counter | undefined;
  hmacSecret?: string | undefined;
}

export function toAuditRow(entry: AuditEntry, now: Date) {
  const ip = entry.context?.ip;
  const userAgent = entry.context?.userAgent;
  const requestId = entry.context?.requestId;
  return {
    id: uuidv7(),
    occurredAt: now,
    actorUserId: entry.actorUserId,
    action: entry.action,
    targetType: entry.targetType,
    targetId: entry.targetId ?? null,
    // The column is inet: anything that is not a valid address is stored as null.
    ip: typeof ip === 'string' && isIP(ip) !== 0 ? ip : null,
    userAgent: userAgent ? userAgent.slice(0, USER_AGENT_MAX) : null,
    requestId: typeof requestId === 'string' && REQUEST_ID.test(requestId) ? requestId : null,
    metadata: sanitizeAuditMetadata(entry.metadata),
  };
}

function toEntry(row: AuditRow): AuditLogEntry {
  return {
    id: row.id,
    occurredAt: row.occurredAt.toISOString(),
    actor: row.actorUserId === null ? null : { id: row.actorUserId, email: row.actorEmail ?? '' },
    action: row.action,
    target: { type: row.targetType, id: row.targetId },
    ip: row.ip,
    userAgent: row.userAgent,
    requestId: row.requestId,
    metadata: row.metadata,
  };
}

export class AuditService implements AuditRecorder {
  constructor(private readonly deps: AuditServiceDeps) {}

  /**
   * Writes inside the caller's transaction, so an admin action and its audit row commit or roll
   * back together (C-07). Errors propagate and abort the action.
   */
  async recordIn(trx: DbHandle, entry: AuditEntry): Promise<void> {
    await createAuditRepository(trx).insert(toAuditRow(entry, this.deps.clock.now()));
  }

  /** Best-effort write in its own statement: failures are logged and counted, never thrown. */
  async record(entry: AuditEntry): Promise<void> {
    try {
      await createAuditRepository(this.deps.db).insert(toAuditRow(entry, this.deps.clock.now()));
    } catch (error) {
      this.deps.failures?.inc();
      this.deps.logger?.error({ err: error, auditAction: entry.action }, 'audit write failed');
    }
  }

  pseudonymize(email: string): string | undefined {
    const secret = this.deps.hmacSecret;
    if (!secret) return undefined;
    return createHmac('sha256', secret).update(email.trim().toLowerCase()).digest('hex');
  }

  /** Admin query (AP-14). `actorEmail` is resolved to an id first, then the actor index is used. */
  async list(query: ListAuditLogsQuery): Promise<AuditLogPage> {
    const repository = createAuditRepository(this.deps.db);
    const after = query.cursor ? decodeAuditCursor(query.cursor, query) : undefined;

    let actorUserId = query.actorId;
    if (query.actorEmail !== undefined) {
      const found = await repository.findUserIdByEmail(query.actorEmail);
      // Unknown email: nothing can match. A second actor filter must agree with the first.
      if (found === null || (actorUserId !== undefined && actorUserId !== found)) {
        return { items: [], nextCursor: null };
      }
      actorUserId = found;
    }

    const rows = await repository.query({
      actorUserId,
      actions: query.action,
      targetType: query.targetType,
      targetId: query.targetId,
      occurredFrom: query.from ? new Date(`${query.from}T00:00:00.000Z`) : undefined,
      occurredBefore: query.to ? new Date(`${addDays(query.to, 1)}T00:00:00.000Z`) : undefined,
      after,
      limit: query.limit,
    });
    const hasMore = rows.length > query.limit;
    const page = hasMore ? rows.slice(0, query.limit) : rows;
    const last = page[page.length - 1];
    return {
      items: page.map(toEntry),
      nextCursor:
        hasMore && last
          ? encodeAuditCursor(query, { occurredAt: last.occurredAt.toISOString(), id: last.id })
          : null,
    };
  }
}
